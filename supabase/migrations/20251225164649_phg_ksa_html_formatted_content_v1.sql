<h2>Frequently Asked Questions</h2>

<h3>Can I carry over my unused leave?</h3>

<p>Yes, with approval.</p>

<p>Colleagues may carry over a maximum of 15 days to the following calendar year. This requires a written agreement with your Department Head. The agreement must be submitted to Human Resources for record-keeping. Carried-over leave must be used within the first six months of the new year.</p>

<h3>Am I entitled to leave salary before I travel?</h3>

<p>Yes.</p>

<p>Leave salary is processed and disbursed with the final payroll cycle prior to your departure date. Submit your approved leave documentation to Payroll at least 14 days before departure. This ensures timely processing of your leave salary.</p>

<h3>Can I split my annual leave into multiple periods?</h3>

<p>Yes, subject to operational requirements.</p>

<p>You may request to split your leave into two or more periods. Each period should be at least seven consecutive days. All periods must be approved by your Department Head. Total leave taken cannot exceed your annual entitlement.</p>

<h3>What happens to my unused leave if I resign?</h3>

<p>You will be compensated for unused leave.</p>

<p>Upon resignation, all accrued but unused leave will be calculated. You will receive payment for this leave in your final settlement. The calculation is based on your basic salary at the time of resignation. This is a legal requirement under KSA Labor Law.</p>

<h3>Can I take unpaid leave?</h3>

<p>Unpaid leave may be granted in exceptional circumstances.</p>

<p>You must submit a written request to your Department Head. The request must include justification and proposed duration. Approval is at the discretion of management. Unpaid leave does not count toward service time for benefits.</p>

<h3>What if I need emergency leave?</h3>

<p>Emergency leave is available for urgent family matters.</p>

<p>Contact your Department Head immediately. Provide documentation of the emergency when possible. Emergency leave may be deducted from your annual leave balance. In exceptional cases, advance leave may be granted.</p>

