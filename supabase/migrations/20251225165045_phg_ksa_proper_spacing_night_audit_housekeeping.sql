**Primary Audience:** Assistant Executive Housekeepers, Floor Supervisors, Guest Room Attendants

**Objective:** To deliver a "Never Lived In" sensory experience that adheres to Prime Hotels Group 5-Star hygiene and presentation protocols.

---

## Preparation and Sanitization Protocols

Efficiency in housekeeping is rooted in organized preparation. Every attendant must ensure their workstation is correctly commissioned before entering the guest floor.

### Workstation Check

Verify that your trolley is fully stocked.

1. Check that you have sufficient high-thread-count linen for your assigned rooms.

2. Verify that all PHG signature amenities are stocked.

3. Ensure you have a complete set of color-coded microfiber cloths.

4. Confirm that all cleaning chemicals are at proper dilution levels.

### Chemical Safety

All sanitization agents must be dilution-control compliant.

1. Check the concentration levels of all cleaning solutions.

2. Ensure that spray bottles are properly labeled.

3. Never mix different chemical products.

4. Keep Material Safety Data Sheets accessible on your trolley.

### The Silent Entry

Protect guest privacy at all times.

1. Knock three times on the guest room door.

2. Announce "Housekeeping" clearly in a professional voice.

3. Wait five seconds for a response.

4. If the Privacy indicator is active, document the time and move to the next assigned room.

> **Supervisor''s Tip:** Ventilation is the first step to a fresh room. Open all curtains and balcony doors immediately upon entry. This allows natural air circulation while you strip the linen.

---

## The Core Sequence

Follow this sequence exactly for every guest room.

### Step 01: Stripping

Remove all soiled items from the room.

1. Strip all bed linen and place in the soiled linen bag.

2. Remove all used towels from the bathroom.

3. High-dust the headboard and bed frame.

4. Check under the bed for any guest items.

### Step 02: Sanitization

Pre-treat all bathroom fixtures.

1. Apply cleaning solution to the toilet bowl.

2. Spray all sink and shower fixtures.

3. Allow the chemical to work for five minutes.

4. Focus on high-touch points including door handles and light switches.

### Step 03: Bed Making

Use the PHG Triple Sheet method.

1. Place the fitted sheet with hospital corners at precisely 45 degrees.

2. Add the flat sheet with the top fold aligned to the headboard.

3. Place the duvet with even overhang on both sides.

4. Arrange pillows according to the PHG standard layout.

### Step 04: Restorative Dusting

Clean all surfaces using the clockwise method.

1. Start from the entrance and work clockwise around the room.

2. Dust from top to bottom on all surfaces.

3. Use green-coded cloths for wooden furniture.

4. Pay special attention to picture frames and decorative items.

### Step 05: Polishing

Achieve a mirror finish on all chrome fixtures.

1. Polish all bathroom chrome until water spots are eliminated.

2. Clean all mirrors to a streak-free finish.

3. Use blue-coded cloths for glass and mirrors.

4. Buff all fixtures to a high shine.

### Step 06: Amenity Reset

Align all items to the Master Layout standard.

1. Replace all bathroom amenities to the approved positions.

2. Ensure all stationery is properly aligned on the desk.

3. Check that the minibar is fully stocked and organized.

4. Verify that all glassware is clean and properly positioned.

### Step 07: Vacuuming

Achieve a deep clean finish on all carpeted areas.

1. Start from the furthest corner of the room.

2. Work your way toward the door.

3. Use overlapping strokes for complete coverage.

4. Pay special attention to corners and edges.

### Step 08: Final Sweep

Remove any remaining debris.

1. Use a sticky roller to remove any hair or lint from the carpet.

2. Check all corners and under furniture.

3. Ensure the bathroom floor is completely dry.

4. Remove any water spots from the floor.

---

## The Sensory Signature

Before requesting a supervisor inspection, verify the PHG Sensory Signature.

### Olfactory Standard

Apply the signature scent.

1. Stand in the center of the room.

2. Apply two mists of PHG Signature Oud at head height.

3. Allow the scent to disperse naturally.

4. Do not over-apply.

### Thermal Standard

Set the climate control to the welcoming temperature.

1. Reset the thermostat to 22 degrees Celsius.

2. This is the regional KSA standard for guest comfort.

3. Ensure the air conditioning is functioning properly.

4. Check that all vents are unobstructed.

### Illumination Standard

Set the lighting to the Welcome Scene.

1. Turn on Lamp 1 and Lamp 2.

2. Ensure the entry light is on.

3. Set curtains to the half-open welcome position.

4. Check that all bulbs are functioning.

---

## Health and Safety

**Color Coding Matrix**

Use the correct cloth for each area to prevent cross-contamination.

**Red Cloth:** Toilet and urinal area only

**Yellow Cloth:** Sinks and shower tiles

**Blue Cloth:** Mirrors, glass, and television screens

**Green Cloth:** General furniture and dusting

> **Critical Warning:** Never mix cleaning chemicals. Cross-contamination can create dangerous fumes and compromise guest safety.

