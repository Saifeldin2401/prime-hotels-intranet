**Primary Audience:** Night Auditors, Front Office Managers, Assistant Front Office Managers

**Objective:** To ensure accurate reconciliation of daily revenue and successful transition of the Property Management System to the next business date.

---

## Preparation and Pre-Audit Checks

**Time Frame:** 23:00 - 01:00

The success of the night audit depends on the accuracy of the day''s records. Before initiating the automated cycle, complete the following manual verifications.

### Guest Status Finalization

Review all departures and ensure proper closure.

1. Identify all guests who were scheduled to depart but did not check out.

2. Process any remaining charges to their folios.

3. Verify that all checked-out guest folios show a zero balance.

### No-Show Management

Review the arrival list for guests who have not checked in.

1. Identify any reservations where the guest has not arrived by 01:00.

2. Update their status to "No-Show" in the system.

3. Apply the appropriate cancellation fees according to property policy.

### Revenue Reconciliation

Ensure all outlet revenues are properly recorded.

1. Verify that all Food and Beverage outlets have closed their POS systems.

2. Confirm that Spa and other revenue centers have submitted their end-of-day reports.

3. Check that all outlet receipts match the totals in the PMS interface.

### Master Folios

Review all house accounts and internal billing.

1. Verify that all master folios used for internal expenses are current.

2. Ensure that departmental charges have been properly allocated.

3. Clear any temporary holds or pending transactions.

> **Auditor''s Tip:** Start your room rate audit around 22:30. Identifying billing errors early saves significant time during the high-pressure audit execution phase.

---

## The Audit Execution Phase

Once all pre-checks are confirmed, proceed to the main audit module in the Property Management System.

### Pre-Audit Reporting

Generate backup reports before starting the automated process.

1. Print the House Status report.

2. Print the Guest In-House report.

3. Keep these physical records available in case of system interruption during the batch process.

### Trial Balance Review

Verify the financial accuracy of all transactions.

1. Open the Trial Balance report in the PMS.

2. Ensure that total debits equal total credits.

3. Investigate any discrepancies before proceeding.

> **Critical:** If the system reports a "Financial Imbalance" error, do NOT attempt to force the date roll. Halt the process immediately and contact the IT Duty Manager and the Director of Finance.

### Posting Room and Tax

Execute the automated posting process.

1. Initiate the batch posting for all occupied rooms.

2. Verify that room charges post correctly to each folio.

3. Confirm that applicable taxes are calculated and posted.

### Systems Audit

Allow the system to perform its internal checks.

1. The system will check for any open shifts.

2. It will identify any unposted charges.

3. Resolve any blocking alerts immediately before proceeding.

### Rolling the Business Date

Complete the transition to the new business day.

1. Review the final summary screen.

2. Confirm the date change when prompted.

3. The system will now transition to the new business day.

---

## Post-Audit and Financial Reporting

**Time Frame:** 03:00 - 05:00

After the system rolls over, focus on auditing the accuracy of the closure and preparing management reports.

### Night Manager''s Log

Document the night''s activities for the morning team.

1. Record any significant incidents that occurred during the shift.

2. Note any guest complaints and their resolution status.

3. Document any system issues or technical problems.

4. This log is the primary communication tool for the Daily Morning Briefing.

### Management Reporting Kit

Prepare the digital audit pack for senior management.

**The Manager''s Flash Report**

This report provides an overview of the day''s performance.

- Final occupancy percentage

- Average Daily Rate

- Revenue Per Available Room

**High Balance Report**

This report flags financial risk.

- Identifies guest folios approaching credit limits

- Lists folios exceeding authorized thresholds

- Requires immediate follow-up by the Front Office Manager

**Market Segment Report**

This report shows revenue by source.

- Breakdown of production by booking channel

- Corporate versus leisure guest mix

- Group versus transient analysis

### Systems Backup Verification

Confirm that all data is properly secured.

1. Check that the automated cloud backup has initiated successfully.

2. Verify the backup completion status.

3. Note any backup errors in the Night Manager''s Log.

> **Warning:** Ensure that all physical registration cards for the day''s arrivals are filed securely. Any printed guest ID copies must be processed for shredding in accordance with KSA Privacy Laws and PDPL requirements.

---

## Handover Protocol

A smooth transition to the morning shift is vital for operational continuity.

### Physical Handover

Transfer all duty items to the incoming shift.

1. Hand over the Duty Manager mobile phone.

2. Transfer all master keys to the Morning Shift Lead.

3. Provide the key log for signature.

### Operational Briefing

Brief the morning team on critical information.

1. Review expected early arrivals.

2. Highlight any VIP-1 guests checking in.

3. Discuss any ongoing maintenance issues.

4. Note any guest complaints requiring follow-up.

### Financial Handover

Complete the cash reconciliation.

1. Count the Petty Cash float with the incoming shift.

2. Both shifts must sign the handover log.

3. Secure all cash in the designated safe.

