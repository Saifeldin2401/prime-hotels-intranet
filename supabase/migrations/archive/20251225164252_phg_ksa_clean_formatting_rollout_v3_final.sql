## Frequently Asked Questions

### Can I carry over my unused leave?

Yes, with approval.

Colleagues may carry over a maximum of 15 days to the following calendar year.

This requires a written agreement with your Department Head.

The agreement must be submitted to Human Resources for record-keeping.

Carried-over leave must be used within the first six months of the new year.

### Am I entitled to leave salary before I travel?

Yes.

Leave salary is processed and disbursed with the final payroll cycle prior to your departure date.

Submit your approved leave documentation to Payroll at least 14 days before departure.

This ensures timely processing of your leave salary.

### Can I split my annual leave into multiple periods?

Yes, subject to operational requirements.

You may request to split your leave into two or more periods.

Each period should be at least seven consecutive days.

All periods must be approved by your Department Head.

Total leave taken cannot exceed your annual entitlement.

### What happens to my unused leave if I resign?

You will be compensated for unused leave.

Upon resignation, all accrued but unused leave will be calculated.

You will receive payment for this leave in your final settlement.

The calculation is based on your basic salary at the time of resignation.

This is a legal requirement under KSA Labor Law.

### Can I take unpaid leave?

Unpaid leave may be granted in exceptional circumstances.

You must submit a written request to your Department Head.

The request must include justification and proposed duration.

Approval is at the discretion of management.

Unpaid leave does not count toward service time for benefits.

### What if I need emergency leave?

Emergency leave is available for urgent family matters.

Contact your Department Head immediately.

Provide documentation of the emergency when possible.

Emergency leave may be deducted from your annual leave balance.

In exceptional cases, advance leave may be granted.

---

