## Annual Leave Entitlement

At Prime Hotels Group, we recognize the importance of rest and rejuvenation for our colleagues.

### Legal Entitlement

As per KSA Labor Law statutes, all colleagues are entitled to:

1. 30 calendar days of paid annual leave per year.

2. Leave accrues from your first day of employment.

3. Leave cannot be waived or forfeited without written agreement.

4. Unused leave may be carried over subject to management approval.

### Requesting Leave

Submit your leave request through the proper channels.

**Advance Notice**

1. Submit requests via the Colleague Portal.

2. Requests should be submitted at least 45 days in advance.

3. This allows us to manage departmental coverage effectively.

4. Early submission increases the likelihood of approval for your preferred dates.

**Peak Season Restrictions**

Leave is subject to operational requirements.

1. Limited leave is available during Ramadan.

2. Restricted leave during Eid periods.

3. Minimal leave during Hajj season.

4. Your Department Head will communicate blackout dates in advance.

### Leave Approval Process

Your request will be reviewed by your Department Head.

1. Requests are evaluated based on operational needs.

2. Seniority and rotation are considered.

3. You will receive approval or denial within 14 days.

4. Approved leave will be confirmed in writing.

**HR Director''s Note:** Planning your leave early allows us to manage departmental coverage effectively and ensures you get your preferred dates.

