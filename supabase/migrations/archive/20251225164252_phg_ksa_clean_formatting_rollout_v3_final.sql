## Air Ticket Benefit

We facilitate travel for our international colleagues to visit their home countries.

### Entitlement

The air ticket benefit is provided based on length of service.

**Eligibility**

1. One return economy air ticket to your home destination.

2. Provided for every two years of completed service.

3. Home destination is defined as your country of passport origin.

4. Ticket class is economy unless otherwise specified in your contract.

### Booking Process

All travel must be coordinated through the HR Travel Desk.

**How to Book**

1. Submit your travel request at least 60 days before your intended departure.

2. Provide your preferred travel dates.

3. The HR Travel Desk will coordinate with corporate travel partners.

4. You will receive your ticket confirmation within 14 days.

**Travel Dates**

1. Travel must coincide with your approved annual leave.

2. You cannot use the ticket benefit without taking leave.

3. Travel dates must be confirmed at least 30 days in advance.

4. Changes to confirmed tickets may incur fees.

### Encashment Option

In specific circumstances, ticket encashment may be permitted.

**Encashment Criteria**

1. You must have completed at least two years of service.

2. You must not have used the ticket benefit in the current cycle.

3. Approval is required from both the General Manager and Regional HR Director.

4. Encashment value is based on the economy ticket rate to your home destination.

**Application Process**

1. Submit a written request to your Department Head.

2. Provide justification for the encashment request.

3. The request will be forwarded to the General Manager for review.

4. You will receive a decision within 21 days.

