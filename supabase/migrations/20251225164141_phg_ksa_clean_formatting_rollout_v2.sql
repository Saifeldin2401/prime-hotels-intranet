## Legal Mandate and Purpose

This policy establishes the mandatory standards for the collection, processing, and storage of Personally Identifiable Information within Prime Hotels Group.

Adherence to this policy is non-negotiable. It aligns with the KSA Personal Data Protection Law and international data sovereignty standards.

All employees must understand and comply with these requirements as a condition of employment.

---

## Core Governance Principles

### The Principle of Purpose

Staff are authorized to access guest data only for specific business purposes.

**Authorized Access**

You may access guest information when:

1. Actively facilitating a guest transaction.

2. Responding to a direct guest request.

3. Performing your assigned job duties.

4. Authorized by your department head for a specific purpose.

**Prohibited Access**

You may NOT access guest information for:

1. Personal curiosity or browsing.

2. Sharing with unauthorized third parties.

3. Any purpose unrelated to your job duties.

4. Marketing or promotional purposes without explicit consent.

**Strict Prohibition:** Unauthorized browsing of guest history is a violation of the PHG Code of Ethics and may result in disciplinary action up to and including termination.

### Transactional Security

Protect guest information during all transactions.

**At the Front Desk**

1. Never leave registration cards visible to other guests.

2. Turn documents face-down immediately after guest signature.

3. Do not discuss guest information in public areas.

4. Shield the computer screen from public view when accessing guest data.

**During Check-In and Check-Out**

1. Verify guest identity discreetly.

2. Process payment information out of sight of other guests.

3. Hand documents directly to the guest.

4. Never leave guest information unattended on the desk.

**Mobile Device Prohibition**

The use of personal mobile devices to capture images of guest documents is strictly prohibited.

1. Never photograph guest ID documents.

2. Never photograph credit cards or payment information.

3. Never photograph registration cards or folios.

4. All scanning must be performed using approved property hardware.

**Consequence:** Violation of the mobile device prohibition is a summary dismissal offense under the PHG Code of Conduct.

---

## Data Retention and Secure Disposal

Operating in the Kingdom of Saudi Arabia requires specific document retention periods and disposal methods.

### Digital Records

All electronic guest data must be properly secured.

**Encryption Requirements**

1. All guest data must be encrypted at rest.

2. Sensitive fields must be masked in public UI views.

3. Access logs must be maintained for all guest data queries.

4. Regular security audits are conducted by the IT Department.

### Physical Records

All printed materials containing guest information must be handled securely.

**Secure Disposal Process**

1. Any printed guest lists must be deposited in Certified Secure Destruction bins.

2. Folio drafts and registration card copies must be shredded within 24 hours.

3. Never place guest information in regular waste bins.

4. Disposal must occur at the end of every shift.

**Document Retention**

1. Registration cards must be scanned into the system.

2. Original cards must be shredded within 24 hours of scanning.

3. Daily reports containing guest information must be filed securely.

4. Retention periods follow KSA legal requirements.

### External Verification Requests

Never confirm guest occupancy to third parties without proper authorization.

**Telephone Inquiries**

1. Never confirm if a guest is staying at the property.

2. Never provide room numbers to callers.

3. Transfer calls directly to the room without verbal confirmation.

4. If the caller insists on confirmation, refer them to the Front Office Manager.

**In-Person Inquiries**

1. Never provide guest information to visitors.

2. Contact the guest directly to verify if they are expecting a visitor.

3. Follow the property protocol for visitor management.

4. Document all unusual requests in the shift log.

**Government and Legal Requests**

1. Only respond to requests with a verified government-issued warrant.

2. Contact the General Manager immediately.

3. Refer all legal requests to the Legal and Compliance Department.

4. Never release information without proper authorization.

---

## Compliance Accountability

Department Heads are responsible for ensuring 100 percent policy awareness within their teams.

### Training Requirements

1. All new employees must complete privacy training during orientation.

2. Annual refresher training is mandatory for all staff.

3. Department Heads must maintain training records.

4. Compliance certificates must be filed with Human Resources.

### Audit and Monitoring

Random audits are conducted to ensure compliance.

1. PMS access logs are reviewed monthly by the Regional Compliance Office.

2. Unusual access patterns trigger immediate investigation.

3. All violations are reported to senior management.

4. Disciplinary action is taken for policy violations.

### Legal Consequences

This policy is part of your mandatory employment contract.

1. Violations may result in disciplinary action.

2. Serious violations may lead to termination of employment.

3. Criminal violations may result in legal action under KSA PDPL statutes.

4. The company will cooperate fully with law enforcement in cases of data breach.

---

**Compliance Notice:** Failure to comply with this policy may lead to legal action under KSA Personal Data Protection Law statutes.

