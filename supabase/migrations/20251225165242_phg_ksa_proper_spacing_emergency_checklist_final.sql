## Evacuation and Crowd Control

### Stairwell Usage

Always use designated fire stairs during evacuation.

1. Pressurized fire stairs are the safest route.

2. Never use elevators during Code Red or Code Orange.

3. Assist guests who need mobility support.

4. Keep stairwells clear of obstructions.

### Guest Communication

Use firm but reassuring language.

**English:** "Please follow me to the safe assembly area."

**Arabic:** "يرجى اتباعي إلى منطقة التجمع الآمنة"

**Communication Guidelines**

1. Speak clearly and calmly.

2. Do not use alarming language.

3. Provide simple, direct instructions.

4. Reassure guests that they are safe.

### Accountability

Department Heads must account for all staff.

1. Proceed to the designated assembly point.

2. Take a headcount of your team.

3. Report to the Duty Manager within 10 minutes of evacuation.

4. Do not leave the assembly point until given the all-clear.

---

## Responder Obligations

### Stay Calm

Your demeanor sets the tone for guest safety.

1. Take a deep breath before responding.

2. Speak in a calm, confident voice.

3. Do not show panic or fear.

4. Guests will follow your lead.

### Report Clearly

Use clear, concise radio communication.

1. State your name and location.

2. Describe the emergency briefly.

3. Request specific assistance.

4. Acknowledge all instructions.

### Direct Safely

Guide guests to the nearest safe assembly point.

1. Know all evacuation routes from your work area.

2. Identify guests who may need assistance.

3. Keep groups together during evacuation.

4. Do not allow guests to return to their rooms.

---

> **Warning:** Failure to adhere to Civil Defense protocols can result in property-wide fines and legal liability for individual staff members.

