## Code Definitions and Immediate Actions

### Code Red: Fire or Smoke

**Threat Type:** Active fire or smoke detected

**Immediate Protocol**

Follow the RACE procedure:

**R - Rescue**

1. Assist any guests or staff in immediate danger.

2. Move them away from the fire or smoke.

3. Do not put yourself at risk.

4. Account for all persons in your area.

**A - Alarm**

1. Activate the nearest fire alarm pull station.

2. Call 999 to alert Security Command Center.

3. State your location clearly.

4. Describe the nature and extent of the fire.

**C - Contain**

1. Close all doors to contain the fire.

2. Do not lock doors.

3. Close windows if safe to do so.

4. Do not use elevators.

**E - Extinguish or Evacuate**

1. If the fire is small and you are trained, use the appropriate fire extinguisher.

2. If the fire is large or spreading, evacuate immediately.

3. Follow the evacuation route to Assembly Point A.

4. Do not re-enter the building.

> **Critical:** Use pressurized fire stairs only. Never use elevators during Code Red.

### Code Blue: Medical Emergency

**Threat Type:** Guest or staff member requires immediate medical attention

**Immediate Protocol**

1. Do not move the patient unless they are in immediate danger.

2. Call 999 and request the AED and on-site nurse.

3. Stay with the patient and provide reassurance.

4. Clear the area of bystanders.

5. If trained, begin first aid or CPR as appropriate.

6. Wait for medical professionals to arrive.

> **Note:** The AED is located at the Front Desk and Security Office.

### Code Orange: Suspicious Package

**Threat Type:** Unattended bag, package, or suspicious item

**Immediate Protocol**

1. Do not touch or move the item.

2. Cordon off the area with a 50-meter perimeter.

3. Use landlines only to communicate.

4. Do not use radios or mobile phones near the suspicious item.

5. Evacuate the immediate area calmly.

6. Call 999 and report to Security Command Center.

7. Wait for Civil Defense bomb disposal unit.

> **Warning:** Radio frequencies can trigger certain explosive devices. Use landlines only.

### Code Black: Armed Intruder or Active Threat

**Threat Type:** Armed individual or active security threat

**Immediate Protocol**

Follow the Run, Hide, Tell procedure:

**Run**

1. If you can safely escape, do so immediately.

2. Leave your belongings behind.

3. Help others escape if possible.

4. Do not attempt to confront the intruder.

**Hide**

1. If you cannot escape, find a secure location.

2. Lock and barricade doors.

3. Turn off lights and silence mobile phones.

4. Stay low and out of sight.

5. Remain silent.

**Tell**

1. Call 999 when it is safe to do so.

2. Provide your location and description of the threat.

3. Follow instructions from Security Command Center.

4. Do not leave your secure location until given the all-clear.

> **Critical:** Property-wide lockdown will be initiated by the Duty Security Officer. Follow all instructions immediately.

