## Compliance Accountability

Department Heads are responsible for ensuring 100 percent policy awareness within their teams.

### Training Requirements

1. All new employees must complete privacy training during orientation.

2. Annual refresher training is mandatory for all staff.

3. Department Heads must maintain training records.

4. Compliance certificates must be filed with Human Resources.

### Audit and Monitoring

Random audits are conducted to ensure compliance.

1. PMS access logs are reviewed monthly by the Regional Compliance Office.

2. Unusual access patterns trigger immediate investigation.

3. All violations are reported to senior management.

4. Disciplinary action is taken for policy violations.

### Legal Consequences

This policy is part of your mandatory employment contract.

1. Violations may result in disciplinary action.

2. Serious violations may lead to termination of employment.

3. Criminal violations may result in legal action under KSA PDPL statutes.

4. The company will cooperate fully with law enforcement in cases of data breach.

